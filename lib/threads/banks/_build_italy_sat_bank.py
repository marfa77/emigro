def main() -> None:
    rows = ROWS[:100]
    assert len(rows) == 100, len(rows)
    out = []
    for i, (pillar, p1) in enumerate(rows, start=1):
        dest = DEST[pillar] if pillar in DEST else DEST[
            {
                "yellow": "yellow",
            }.get(pillar, pillar)
        ]
        # map yellow alias
        if pillar == "yellow":
            dest = DEST["yellow"]
        if pillar == "docs":
            dest = DEST["docs"]
        out.append(
            {
                "d": i,
                "pillar": pillar if pillar != "yellow" else "docs",
                "cta": "satellite",
                "dest": dest,
                "p1": p1.strip(),
                "p2": p2_for(i),
            }
        )
    path = Path(__file__).with_name("emigro-italy-satellite-days.json")
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
    print("wrote", path, "n", len(out))
    print("pillars", Counter(r["pillar"] for r in out))
    print("dests", Counter(r["dest"] for r in out))
    lens = [len(r["p1"]) for r in out]
    print("p1 len min/med/max", min(lens), sorted(lens)[len(lens)//2], max(lens))


