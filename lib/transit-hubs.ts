export function getTransitHub(slug: string): TransitHub | undefined {
  return TRANSIT_HUBS.find((hub) => hub.slug === slug);
}

export function isTransitHubSlug(slug: string): slug is TransitHubSlug {
  return TRANSIT_HUBS.some((hub) => hub.slug === slug);
}

export function getHubsByKind(kind: DestinationHubKind): TransitHub[] {
  return TRANSIT_HUBS.filter((hub) => hub.kind === kind);
}

export function hubKindLabel(kind: DestinationHubKind): string {
  return kind === "settle" ? "Страна для жизни" : "Транзитный хаб";
}
