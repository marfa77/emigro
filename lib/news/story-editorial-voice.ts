/**
 * Editorial voice for short news story tiles.
 * Keep SHORT. Ban both press-wire AND fake-blogger melodrama.
 */
import { voiceExamples } from "@/lib/community-notes/editorial-voice";

/** Compact voice block for Gemini story generation / rewrite. */
export function storyEditorialVoiceForTopic(topicKey: string): string {
  const geo =
    topicKey === "portugal"
      ? "Португалия (AIMA, Finanças, Lisboa/Porto/Braga)"
      : topicKey === "spain"
        ? "Испания (NIE/TIE, extranjería, Valencia/Madrid/Barcelona)"
        : "европейский коридор для релокантов с паспортами RU/BY/UA/KZ";

  return `
ГОЛОС ПЛИТКИ Emigro — спокойный релокант, который уже через это проходил (${geo}).
Пиши коротко и по делу — как в личке другу, НЕ как ТАСС и НЕ как «мотивационный блогер».

Как говорить:
- На «вы». Факты и имена сначала, эмоции — максимум одна короткая фраза.
- Схема: что случилось → что это значит → кого заденет / кого нет.
- Даты календарно («6 августа 2026»). Термины при первом упоминании — с русской расшифровкой в скобках.
- Можно сухая ирония одной фразой. Нельзя — жалость и «душещипательные» обороты.

Запрещено (пресс):
«выражает опасения», «подчеркивает», «это заявление», «в соответствии с», «важно отметить», «на данный момент», «отражает стремление», «стало известно».

Запрещено (фальшивый «живой» тон — так тоже не говорят):
«Представьте:», «Эта новость, конечно, сильно напугала», «усердно строили свою жизнь», «казалось бы, всё должно быть просто, но нет», «будущее под вопросом», «избежать подобных сюрпризов», «Давайте разберемся», «Что это значит для вас?» как клише-заголовок абзаца, «именно с такой ситуацией столкнулись».

Хорошо (тон):
${voiceExamples.goodDemystify}

Плохо:
${voiceExamples.bad}
`.trim();
}
