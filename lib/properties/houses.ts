import type { PropertySource } from "@/lib/properties/types";

/**
 * House quarters on the Portugal satellite (porto.emigro.online/doma): places where you buy a whole house,
 * with nobody above or below. One card per quarter, not per listing — listings come and go, the quarter stays.
 *
 * Same rules as the new-build catalog: a fact we could not confirm stays null and goes to `unknowns`;
 * every listing carries its URL and the day we saw it.
 */

export type QuarterKind = "estate" | "gated";

export type QuarterListing = {
  title: string;
  price_eur: number;
  /** Area as the listing states it (usually área bruta). */
  area_m2: number | null;
  plot_m2: number | null;
  typology: string;
  built: string | null;
  url: string;
  seller: string;
  /** Day we saw it (YYYY-MM-DD). */
  seen: string;
  /** How we know it is in the quarter. */
  where: "pin" | "street" | "named";
  status: "active" | "removed";
  note?: string;
};

export type HouseQuarter = {
  slug: string;
  name: string;
  altName: string | null;
  kind: QuarterKind;
  tagline: string;
  municipality: "Porto" | "Matosinhos" | "Vila Nova de Gaia" | "Maia";
  freguesia: string;
  /** Centre of the OSM outline. */
  lat: number;
  lng: number;
  /** True when the point is approximate (no mapped outline). */
  approx: boolean;
  built: string | null;
  architect: string | null;
  programme: string | null;
  houses: string | null;
  /** What a typical house is, in plain words. */
  houseType: string;
  summary: string;
  listings: QuarterListing[];
  notes: string[];
  unknowns: string[];
  sources: PropertySource[];
  verified: string;
};

